export function getCoursePrerequisites(nodeId: string): Set<string> {
  const visited = new Set<string>();
  const map = new Map(CURRICULUM_NODES.map((n) => [n.id, n]));
  const walk = (id: string) => {
    const node = map.get(id);
    if (!node) return;
    for (const p of node.prerequisites) {
      if (!visited.has(p)) {
        visited.add(p);
        walk(p);
      }
    }
  };
  walk(nodeId);
  return visited;
}

export function getCourseUnlocks(nodeId: string): Set<string> {
  const visited = new Set<string>();
  const walk = (id: string) => {
    for (const node of CURRICULUM_NODES) {
      if (node.prerequisites.includes(id) && !visited.has(node.id)) {
        visited.add(node.id);
        walk(node.id);
      }
    }
  };
  walk(nodeId);
  return visited;
}
